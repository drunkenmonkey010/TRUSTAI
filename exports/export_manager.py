"""Export center: produce CSV / JSON / Excel / Markdown artifacts.

Every export is stamped with the investigation run (where applicable),
timestamp, model/scoring version and an evidence-limitations note.
"""
from __future__ import annotations

import io
import json
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd

from database.connection import Database, get_db
from reports.portfolio_report import PortfolioReport
from reports.vendor_report import VendorReport
from risk.weights import MODEL_VERSION

_LIMITATION = ("Generated by Meridian Vendor AI Intelligence Engine. Findings reflect public "
               "evidence available at retrieval time; absence of evidence is not proof of absence "
               "of AI usage. Verify against original sources.")


def _stamp() -> Dict[str, str]:
    return {"generated_at": datetime.now(timezone.utc).isoformat(),
            "risk_model_version": MODEL_VERSION, "limitations": _LIMITATION}


class ExportManager:
    def __init__(self, db: Optional[Database] = None):
        self.db = db or get_db()

    # ---- helpers ---- #
    def _df(self, sql: str, params=()) -> pd.DataFrame:
        return pd.DataFrame(self.db.query(sql, params))

    def _csv(self, df: pd.DataFrame) -> bytes:
        return df.to_csv(index=False).encode("utf-8")

    def _json(self, payload: Any) -> bytes:
        return json.dumps({"meta": _stamp(), "data": payload}, indent=2, default=str).encode("utf-8")

    def _xlsx(self, sheets: Dict[str, pd.DataFrame]) -> bytes:
        buf = io.BytesIO()
        with pd.ExcelWriter(buf, engine="openpyxl") as xw:
            for name, df in sheets.items():
                (df if not df.empty else pd.DataFrame({"note": ["no data"]})).to_excel(
                    xw, sheet_name=name[:31], index=False)
        return buf.getvalue()

    # ---- datasets ---- #
    def vendor_inventory(self, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT vendor_id, vendor_name, category, website, criticality_tier, "
                      "operational_dependency, data_classification FROM vendors ORDER BY vendor_id")
        return self._emit("vendor_inventory", df, fmt)

    def evidence_ledger(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT * FROM evidence WHERE run_id=? ORDER BY evidence_id", (run_id,))
        return self._emit(f"evidence_ledger_{run_id[:8]}", df, fmt)

    def risk_register(self, fmt: str) -> Tuple[str, bytes]:
        df = self._df(
            "SELECT ra.vendor_id, ra.overall_priority, ra.inherent_risk, ra.residual_risk, "
            "ra.evidence_confidence, ra.investigation_uncertainty, ra.model_version, ra.created_at "
            "FROM risk_assessments ra ORDER BY ra.created_at DESC")
        return self._emit("risk_register", df, fmt)

    def recommendations(self, run_id: Optional[str], fmt: str) -> Tuple[str, bytes]:
        if run_id:
            df = self._df("SELECT * FROM recommendations WHERE run_id=?", (run_id,))
        else:
            df = self._df("SELECT * FROM recommendations")
        return self._emit("recommendations", df, fmt)

    def provider_graph(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT source_entity, relation_type, target_entity, confidence, evidence_status "
                      "FROM vendor_relationships WHERE run_id=?", (run_id,))
        return self._emit(f"provider_graph_{run_id[:8]}", df, fmt)

    def adaptive_trace(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT step, layer, decision, proposed_action, rationale, budget_cost "
                      "FROM adaptive_decisions WHERE run_id=? ORDER BY step", (run_id,))
        return self._emit(f"adaptive_trace_{run_id[:8]}", df, fmt)

    def benchmark_evaluation(self, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT vendor_id, dimension, match_type, automated_value, benchmark_value, notes "
                      "FROM benchmark_evaluations ORDER BY vendor_id, dimension")
        return self._emit("benchmark_evaluation", df, fmt)

    def remediation_register(self, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT vendor_id, severity, status, risk_category, responsible_role, "
                      "due_date, description, recommendation FROM remediation_findings ORDER BY finding_id")
        return self._emit("remediation_register", df, fmt)

    def control_matrix(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT domain, status, evidence_quality, validation_method, confidence, "
                      "required_action, framework_refs FROM control_assessments WHERE run_id=?", (run_id,))
        return self._emit(f"control_matrix_{run_id[:8]}", df, fmt)

    def framework_crosswalk(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT framework, control_identifier, control_objective, status, "
                      "recommended_action FROM framework_mappings WHERE run_id=?", (run_id,))
        return self._emit(f"framework_crosswalk_{run_id[:8]}", df, fmt)

    def questionnaire(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT priority, risk_domain, evidence_gap, question_text, response_type, "
                      "reviewer_role, closure_criteria, status FROM questionnaires WHERE run_id=?", (run_id,))
        return self._emit(f"questionnaire_{run_id[:8]}", df, fmt)

    def threat_scenarios(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT threat, scenario_type, owasp_ref, asset, impact, mitigations, "
                      "human_review FROM threat_scenarios WHERE run_id=?", (run_id,))
        return self._emit(f"threat_scenarios_{run_id[:8]}", df, fmt)

    def snapshot_manifest(self, fmt: str) -> Tuple[str, bytes]:
        df = self._df("SELECT snapshot_id, run_id, vendor_id, schema_version, content_hash, frozen_at "
                      "FROM frozen_snapshots ORDER BY frozen_at DESC")
        return self._emit("snapshot_manifest", df, fmt)

    def vendor_report_markdown(self, run_id: str) -> Tuple[str, bytes]:
        md = VendorReport(self.db).to_markdown(run_id)
        return f"vendor_report_{run_id[:8]}.md", md.encode("utf-8")

    def portfolio_report_markdown(self) -> Tuple[str, bytes]:
        return "portfolio_report.md", PortfolioReport(self.db).to_markdown().encode("utf-8")

    def investigation_report(self, run_id: str, fmt: str) -> Tuple[str, bytes]:
        if fmt == "markdown":
            return self.vendor_report_markdown(run_id)
        data = VendorReport(self.db).build(run_id)
        if fmt == "json":
            return f"investigation_{run_id[:8]}.json", self._json(data)
        # xlsx: multiple sheets
        f = data["findings"]
        sheets = {
            "claims": pd.DataFrame(f.get("claims") or []),
            "evidence": pd.DataFrame(f.get("evidence") or []),
            "relationships": pd.DataFrame(f.get("relationships") or []),
            "recommendations": pd.DataFrame(f.get("recommendations") or []),
        }
        return f"investigation_{run_id[:8]}.xlsx", self._xlsx(sheets)

    # ---- emit ---- #
    def _emit(self, base: str, df: pd.DataFrame, fmt: str) -> Tuple[str, bytes]:
        fmt = fmt.lower()
        if fmt == "csv":
            return f"{base}.csv", self._csv(df)
        if fmt == "json":
            return f"{base}.json", self._json(df.to_dict(orient="records"))
        if fmt in ("excel", "xlsx"):
            return f"{base}.xlsx", self._xlsx({base[:31]: df})
        if fmt in ("markdown", "md"):
            return f"{base}.md", ("# " + base + "\n\n" + df.to_markdown(index=False)).encode("utf-8")
        raise ValueError(f"unsupported format: {fmt}")
